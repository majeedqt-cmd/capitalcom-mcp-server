"""Generate the wiki reference pages from the live server + SDK config/errors.

Credential-free: introspects the in-memory FastMCP server (which starts without
credentials) plus the capital_cli config model and error classes. Writes Markdown
into the repo's wiki/ directory. Run via `make wiki`.
"""

from __future__ import annotations

import asyncio
import sys
from pathlib import Path

WIKI = Path(__file__).resolve().parents[1] / "wiki"
BANNER = "<!-- GENERATED by scripts/gen_wiki.py — do not edit by hand; run `make wiki`. -->"
NOTE = "> ⚠️ **Generated page** — do not edit by hand. Run `make wiki` to regenerate.\n"

_CATEGORIES = [
    ("cap_session_", "Session"),
    ("cap_market_", "Market data"),
    ("cap_account_", "Account"),
    ("cap_trade_", "Trading"),
    ("cap_watchlists_", "Watchlists"),
    ("cap_stream_", "Streaming"),
]


def _category(name: str) -> str:
    for prefix, title in _CATEGORIES:
        if name.startswith(prefix):
            return title
    return "ChatGPT Deep Research adapters"


def _schema_type(spec: dict) -> str:
    if "type" in spec:
        return str(spec["type"])
    if "anyOf" in spec:
        parts = [s.get("type", "any") for s in spec["anyOf"] if s.get("type") != "null"]
        return " | ".join(parts) or "any"
    return "any"


def _schema_default(spec: dict) -> str:
    return f"`{spec['default']!r}`" if "default" in spec else "—"


def _params_table(input_schema: dict | None) -> str:
    schema = input_schema or {}
    props = schema.get("properties", {})
    required = set(schema.get("required", []))
    if not props:
        return "_No parameters._\n"
    rows = ["| Parameter | Type | Required | Default |", "| --- | --- | --- | --- |"]
    for pname, spec in props.items():
        req = "**yes**" if pname in required else "no"
        rows.append(f"| `{pname}` | {_schema_type(spec)} | {req} | {_schema_default(spec)} |")
    return "\n".join(rows) + "\n"


async def _tools_page(client) -> str:
    tools = sorted(await client.list_tools(), key=lambda t: (_category(t.name), t.name))
    out = [
        BANNER, "", "# Tools Reference", "", NOTE,
        "The server exposes these MCP tools. Mutating tools require `confirm=true`; "
        "trades are two-phase (preview → confirm → execute).",
    ]
    current = None
    for t in tools:
        cat = _category(t.name)
        if cat != current:
            out += ["", f"## {cat}", ""]
            current = cat
        out += [f"### `{t.name}`", "", (t.description or "").strip(), "", _params_table(t.inputSchema)]
    return "\n".join(out).rstrip() + "\n"


async def _resources_page(client) -> str:
    resources = await client.list_resources()
    templates = await client.list_resource_templates()
    out = [
        BANNER, "", "# Resources Reference", "", NOTE,
        "Resources are read-only snapshots your client fetches by URI.", "",
        "| URI | What it returns |", "| --- | --- |",
    ]
    for r in sorted(resources, key=lambda r: str(r.uri)):
        out.append(f"| `{r.uri}` | {(r.description or '').strip()} |")
    for t in sorted(templates, key=lambda t: t.uriTemplate):
        out.append(f"| `{t.uriTemplate}` | {(t.description or '').strip()} |")
    return "\n".join(out).rstrip() + "\n"


async def _prompts_page(client) -> str:
    prompts = sorted(await client.list_prompts(), key=lambda p: p.name)
    out = [
        BANNER, "", "# Prompts Reference", "", NOTE,
        "Prompts are reusable workflows your client launches by name. They orchestrate "
        "the tools and never trade on their own.", "",
    ]
    for p in prompts:
        out += [f"### `{p.name}`", "", (p.description or "").strip(), ""]
        args = p.arguments or []
        if args:
            out += ["| Argument | Required |", "| --- | --- |"]
            out += [f"| `{a.name}` | {'**yes**' if a.required else 'no'} |" for a in sorted(args, key=lambda a: a.name)]
            out.append("")
        else:
            out += ["_No arguments._", ""]
    return "\n".join(out).rstrip() + "\n"


def _fmt_default(field) -> str:
    if field.is_required():
        return "**(required)**"
    d = field.default
    d = d.value if hasattr(d, "value") else d
    return f"`{d!r}`"


def _config_page() -> str:
    from capital_cli.sdk import CapitalComConfig

    out = [
        BANNER, "", "# Configuration Reference", "", NOTE,
        "Settings are read from environment variables (or a `.env` file / `CAP_*_CMD` "
        "secret-exec helpers). Names below are the env-var form.", "",
        "| Env var | Type | Default | Description |", "| --- | --- | --- | --- |",
    ]
    for name, field in CapitalComConfig.model_fields.items():
        ann = getattr(field.annotation, "__name__", str(field.annotation))
        desc = (field.description or "").strip() or "—"
        out.append(f"| `{name.upper()}` | {ann} | {_fmt_default(field)} | {desc} |")
    return "\n".join(out).rstrip() + "\n"


def _errors_page() -> str:
    from capital_cli.core import errors as errmod

    seen: dict[str, str] = {}

    def collect(cls) -> None:
        for sub in cls.__subclasses__():
            seen[sub.__name__] = (sub.__doc__ or "").strip().split("\n")[0]
            collect(sub)

    collect(errmod.CapitalCLIError)
    out = [
        BANNER, "", "# Error Reference", "", NOTE,
        "The server surfaces these error types. The **safety-refusal** errors "
        "(`TradingDisabledError`, `EpicNotAllowedError`, `DryRunError`, "
        "`ConfirmRequiredError`, `RiskLimitError`) are expected guardrails, not bugs — "
        "they mean the safety model blocked a request.", "",
        "| Error | Meaning |", "| --- | --- |",
    ]
    for name in sorted(seen):
        out.append(f"| `{name}` | {seen[name] or '—'} |")
    return "\n".join(out).rstrip() + "\n"


async def _amain() -> None:
    from fastmcp import Client

    from capital_mcp.server import mcp

    WIKI.mkdir(parents=True, exist_ok=True)
    async with Client(mcp) as client:
        (WIKI / "Tools-Reference.md").write_text(await _tools_page(client))
        (WIKI / "Resources-Reference.md").write_text(await _resources_page(client))
        (WIKI / "Prompts-Reference.md").write_text(await _prompts_page(client))
    (WIKI / "Configuration-Reference.md").write_text(_config_page())
    (WIKI / "Error-Reference.md").write_text(_errors_page())
    print(f"Wrote 5 reference pages to {WIKI}")


def main(out_dir: str | None = None) -> None:
    global WIKI
    if out_dir:
        WIKI = Path(out_dir)
    asyncio.run(_amain())


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else None)
